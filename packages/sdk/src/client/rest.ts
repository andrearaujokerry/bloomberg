/** A zod schema seen structurally, so the transport never depends on a zod version. */
interface Schema {
  safeParse(data: unknown): { success: boolean; data?: unknown; error?: { issues?: unknown } };
}

interface IndexedRoute {
  readonly id: string;
  readonly group: string | null;
  readonly name: string;
  readonly method: HttpMethod;
  /** normalised (`:code` → `{}`) — the lookup key. */
  readonly path: string;
  /** exactly as `wire/rest` spelled it, `:code` markers intact — what the URL is built from. */
  readonly spelling: string;
  readonly params: Schema | null;
  readonly query: Schema | null;
  readonly body: Schema | null;
  readonly response: Schema | null;
  readonly etag: boolean;
  readonly accept: string | null;
}

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null;
}

function isSchema(v: unknown): v is Schema {
  return isRecord(v) && typeof (v as { safeParse?: unknown }).safeParse === 'function';
}

function isRouteLike(v: unknown): v is RouteDef {
  return (
    isRecord(v) &&
    typeof (v as { method?: unknown }).method === 'string' &&
    typeof (v as { path?: unknown }).path === 'string'
  );
}

/** `/functions/:code/run` and `/functions/{code}/run` index to the same key. */
function normalisePath(path: string): string {
  const withSlash = path.startsWith('/') ? path : `/${path}`;
  const stripped = withSlash.replace(/:[A-Za-z0-9_]+/g, '{}').replace(/\{[A-Za-z0-9_]+\}/g, '{}');
  return stripped.length > 1 && stripped.endsWith('/') ? stripped.slice(0, -1) : stripped;
}

/** API.md L447, L493, L563 — the three routes that answer `304`. */
const DEFAULT_ETAG_PATHS = new Set(['/universe/snapshot', '/functions', '/fields']);

const SAFE_METHODS = new Set<HttpMethod>(['GET', 'HEAD']);

function pick(def: RouteDef, ...keys: readonly string[]): Schema | null {
  const bag = def as unknown as Record<string, unknown>;
  for (const key of keys) {
    const value = bag[key];
    if (isSchema(value)) return value;
  }
  return null;
}

function trimPath(path: string): string {
  const withSlash = path.startsWith('/') ? path : `/${path}`;
  return withSlash.length > 1 && withSlash.endsWith('/') ? withSlash.slice(0, -1) : withSlash;
}

function toIndexedRoute(id: string, def: RouteDef): IndexedRoute {
  const dot = id.lastIndexOf('.');
  const method = def.method.toUpperCase() as HttpMethod;
  const path = normalisePath(def.path);
  const bag = def as unknown as Record<string, unknown>;
  const accept = typeof bag.accept === 'string' ? bag.accept : null;
  const etag =
    typeof def.etag === 'boolean'
      ? def.etag
      : SAFE_METHODS.has(method) && DEFAULT_ETAG_PATHS.has(path);
  return {
    id,
    group: dot > 0 ? id.slice(0, dot) : null,
    name: dot > 0 ? id.slice(dot + 1) : id,
    method,
    path,
    spelling: trimPath(def.path),
    params: pick(def, 'params', 'path'),
    query: pick(def, 'query', 'search'),
    body: pick(def, 'body', 'request', 'input'),
    response: pick(def, 'response', 'result', 'output'),
    etag,
    accept,
  };
}

let routeIndex: Map<string, IndexedRoute> | null = null;
let pathIndex: Map<string, string> | null = null;
let groupIndex: Map<string, IndexedRoute[]> | null = null;

function barrelRegistry(): Record<string, unknown> {
  const barrel = RestBarrel as unknown as Record<string, unknown>;
  const rest = barrel.Rest;
  return isRecord(rest) ? rest : barrel;
}

function buildIndex(): Map<string, IndexedRoute> {
  const routes = new Map<string, IndexedRoute>();
  const paths = new Map<string, string>();
  const groups = new Map<string, IndexedRoute[]>();
  const add = (id: string, def: RouteDef): void => {
    const route = toIndexedRoute(id, def);
    routes.set(id, route);
    const pathKey = `${route.method} ${route.path}`;
    if (!paths.has(pathKey)) paths.set(pathKey, id);
    if (route.group !== null) {
      const bucket = groups.get(route.group);
      if (bucket) bucket.push(route);
      else groups.set(route.group, [route]);
    }
  };
  // Three shapes are accepted, so the generated barrel can be written any of the usual ways:
  //   1. `export const Rest = { Auth: { Login: {...} } }`      → 'Auth.Login'
  //   2. `export * from './auth.js'` (the group object `Auth`) → 'Auth.Login'
  //   3. `export * as auth from './auth.js'` (a namespace that *contains* `Auth`) → 'Auth.Login'
  for (const [key, value] of Object.entries(barrelRegistry())) {
    if (isRouteLike(value)) {
      add(key, value);
      continue;
    }
    if (!isRecord(value)) continue;
    for (const [name, def] of Object.entries(value)) {
      if (isRouteLike(def)) {
        add(`${key}.${name}`, def);
        continue;
      }
      if (!isRecord(def)) continue;
      // A module namespace: the group object one level down names the group.
      for (const [subName, subDef] of Object.entries(def)) {
        if (isRouteLike(subDef) && !routes.has(`${name}.${subName}`)) {
          add(`${name}.${subName}`, subDef);
        }
      }
    }
  }
  routeIndex = routes;
  pathIndex = paths;
  groupIndex = groups;
  return routes;
}

function routes(): Map<string, IndexedRoute> {
  return routeIndex ?? buildIndex();
}

function paths(): Map<string, string> {
  if (pathIndex === null) buildIndex();
  return pathIndex!;
}

function groups(): Map<string, IndexedRoute[]> {
  if (groupIndex === null) buildIndex();
  return groupIndex!;
}

