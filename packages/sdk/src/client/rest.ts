/**
 * One namespace method per route in a group: `Rest.Auth.Login` → `client.auth.login(args)`.
 * Derived from the barrel, so a new route is callable the moment the generator runs.
 */
export type GroupApi<G> = {
  [K in keyof G as G[K] extends RouteLike ? Uncapitalize<K & string> : never]: (
    args?: RouteArgs<G[K]>,
    init?: RequestOptions,
  ) => Promise<RouteResponseOf<G[K]>>;
};

/** `'Auth' | 'Data' | 'Functions' | …` — the group half of every dotted route id. */
export type GroupName = RouteId extends `${infer G}.${string}` ? G : never;

/** The names API.md §10 uses for four of the groups. */
export const GROUP_ALIASES = {
  ref: 'Reference',
  fn: 'Functions',
  messaging: 'Messages',
  workspace: 'Workspaces',
} as const;
export type GroupAliases = typeof GROUP_ALIASES;

export type RestNamespaces = {
  [G in GroupName as Uncapitalize<G>]: GroupApi<GroupOf<G>>;
} & {
  [A in keyof GroupAliases as GroupAliases[A] extends GroupName ? A : never]: GroupApi<
    GroupOf<Extract<GroupAliases[A], string>>
  >;
};

/** The transport-and-dictionary half of API.md §10's `TerminalClient`. */
export interface TerminalClientCore {
  /** raw typed transport — every route in the barrel. */
  readonly rest: RestClient;
  /** WebSocket client (§6). Constructed on first access; WP-13 implements it. */
  readonly live: LiveClient;
  /** dictionary + `format()` (API-07). */
  readonly fields: FieldsApi;
  /** re-export of the core function registry (manifests: params, paramGrammar, live(), csv, help). */
  readonly functions: FunctionRegistry;
  readonly options: Readonly<ClientOptions>;
  status(): Promise<unknown>;
  health(): Promise<unknown>;
  /** closes the WS (when one was opened). */
  close(): void;
}

export type TerminalClient = TerminalClientCore & RestNamespaces;

function buildNamespaces(rest: RestClient): Record<string, Record<string, unknown>> {
  const out: Record<string, Record<string, unknown>> = {};
  for (const [group, list] of groups()) {
    const api: Record<string, unknown> = {};
    for (const route of list) {
      api[uncapitalise(route.name)] = (
        args?: AnyRouteArgs,
        init?: RequestOptions,
      ): Promise<unknown> => rest.call(route.id, args, init);
    }
    out[uncapitalise(group)] = api;
  }
  for (const [alias, group] of Object.entries(GROUP_ALIASES)) {
    const api = out[uncapitalise(group)];
    if (api !== undefined) out[alias] = api;
  }
  return out;
}

/** API.md §10 L1239. */
export function createClient(opts: ClientOptions): TerminalClient {
  const rest = new RestClient(opts);
  const fields = createFieldsApi({
    rest,
    ...(opts.fieldsSeed ? { seed: opts.fieldsSeed } : {}),
    ...(opts.format ? { format: opts.format } : {}),
  });

  // `LiveClient` is a WP-13 stub whose constructor throws: build it only when `client.live` (or
  // anything that needs the socket) is actually touched, so REST-only callers are unaffected.
  let live: LiveClient | null = null;

  const client: Record<string, unknown> = { ...buildNamespaces(rest) };
  Object.assign(client, {
    rest,
    fields,
    functions: registry,
    options: rest.options,
    status: (): Promise<unknown> => callByPath(rest, 'GET', '/status'),
    health: (): Promise<unknown> => callByPath(rest, 'GET', '/health'),
    close: (): void => {
      if (live !== null) live.close();
    },
  });
  Object.defineProperty(client, 'live', {
    enumerable: true,
    configurable: true,
    get(): LiveClient {
      live ??= new LiveClient(rest.options);
      return live;
    },
  });
  return client as unknown as TerminalClient;
}

function callByPath(rest: RestClient, method: HttpMethod, path: string): Promise<unknown> {
  const id = rest.routeIdFor(method, path);
  if (id === undefined) {
    return Promise.reject(
      new TerminalApiError({
        code: 'NOT_FOUND',
        message: `wire/rest declares no route for ${method} ${path}`,
        status: 0,
        traceId: defaultTraceId(),
      }),
    );
  }
  return rest.call(id);
}
