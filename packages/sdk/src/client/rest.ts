export class RestClient {
  readonly options: Readonly<ClientOptions>;
  readonly baseUrl: string;

  #fetch: typeof fetch;
  #cache = new Map<string, CacheEntry>();
  #version: VersionEvent | null = null;

  constructor(opts: ClientOptions) {
    if (typeof opts.baseUrl !== 'string' || opts.baseUrl.length === 0) {
      throw new TypeError('ClientOptions.baseUrl is required');
    }
    if (typeof opts.clientVersion !== 'string' || opts.clientVersion.length === 0) {
      throw new TypeError("ClientOptions.clientVersion is required (e.g. 'sdk-js/0.1.0')");
    }
    this.options = { ...opts };
    this.baseUrl = `${opts.baseUrl.replace(/\/+$/, '')}/api/v1`;
    const injected = opts.fetch ?? globalThis.fetch;
    if (typeof injected !== 'function') {
      throw new TypeError('No fetch implementation: pass ClientOptions.fetch');
    }
    this.#fetch = injected.bind(globalThis);
  }

  /** Every route id the generated barrel declares, sorted. */
  get routeIds(): readonly string[] {
    return [...routes().keys()].sort();
  }

  has(routeId: string): boolean {
    return routes().has(routeId);
  }

  /** The route id for a `(method, path)` pair; `:code` and `{code}` both match. */
  routeIdFor(method: HttpMethod, path: string): string | undefined {
    return paths().get(`${method.toUpperCase()} ${normalisePath(path)}`);
  }

  /** The group names the barrel declares (`'Auth'`, `'Reference'`, …). */
  get groupNames(): readonly string[] {
    return [...groups().keys()].sort();
  }

  /** The route ids in one group. */
  groupRouteIds(group: string): readonly string[] {
    return (groups().get(group) ?? []).map((r) => r.id);
  }

  /** Drop the conditional-request cache (after a logout, or a dictionary bump). */
  clearCache(): void {
    this.#cache.clear();
  }

  /**
   * The absolute URL a route resolves to — used by `fn.csvUrl()` / `watchlists.exportCsvUrl()`,
   * which navigate the browser rather than fetching (API.md L1264).
   */
  url(routeId: string, args: AnyRouteArgs = {}): string {
    const traceId = this.#traceId();
    const route = this.#route(routeId, traceId);
    return this.#url(route, args.params, args.query, traceId);
  }

  /** Typed request — `RouteId`, `RouteArgs` and the response all come from the barrel. */
  request<Id extends RouteId>(
    route: Id,
    args?: RouteArgs<RouteDefOf<Id>>,
    init?: RequestOptions,
  ): Promise<RouteResponse<Id>> {
    return this.call(route, args, init) as Promise<RouteResponse<Id>>;
  }

  /** Untyped request, for the convenience namespaces and for callers holding a string id. */
  async call(
    routeId: string,
    args: AnyRouteArgs = {},
    init: RequestOptions = {},
  ): Promise<unknown> {
    const traceId = init.traceId ?? this.#traceId();
    const route = this.#route(routeId, traceId);
    const params = this.#validate(route, 'params', args.params, traceId);
    const query = this.#validate(route, 'query', args.query, traceId);
    const raw = isRawBody(args.body);
    const body = raw ? args.body : this.#validate(route, 'body', args.body, traceId);
    const url = this.#url(route, params, query, traceId);

    const headers: Record<string, string> = {
      accept: init.accept ?? route.accept ?? 'application/json',
      'x-trace-id': traceId,
      'x-client-version': this.options.clientVersion,
    };
    if (this.options.token !== undefined && this.options.token !== '') {
      headers.authorization = `Bearer ${this.options.token}`;
    } else if (!SAFE_METHODS.has(route.method)) {
      // Cookie mode: CSRF defence of API.md §0 L59.
      headers['x-requested-with'] = 'terminal';
    }
    if (body !== undefined && !raw) headers['content-type'] = 'application/json';
    for (const [k, v] of Object.entries(this.options.headers ?? {})) headers[k.toLowerCase()] = v;
    for (const [k, v] of Object.entries(init.headers ?? {})) headers[k.toLowerCase()] = v;

    const cacheable = route.etag && this.options.cacheEtags !== false;
    const cacheKey = `${route.id} ${url}`;
    const cached = cacheable ? this.#cache.get(cacheKey) : undefined;
    if (cached !== undefined) headers['if-none-match'] = cached.etag;

    const request: RequestInit = {
      method: route.method,
      headers,
      ...(body === undefined ? {} : { body: raw ? (body as BodyInit) : JSON.stringify(body) }),
      ...(init.signal ? { signal: init.signal } : {}),
      ...(this.options.token !== undefined && this.options.token !== ''
        ? {}
        : { credentials: this.options.credentials ?? 'include' }),
    };

    const started = now();
    let res: Response;
    try {
      res = await this.#fetch(url, request);
    } catch (err) {
      if (err instanceof Error && err.name === 'AbortError') throw err;
      const ms = now() - started;
      this.#trace({ traceId, route: route.id, ms, status: 0, errorCode: 'PROVIDER_UNAVAILABLE' });
      throw new TerminalApiError({
        code: 'PROVIDER_UNAVAILABLE',
        message: `network error calling ${route.method} ${route.path}: ${
          err instanceof Error ? err.message : String(err)
        }`,
        status: 0,
        traceId,
        retryable: true,
        details: { kind: 'network' },
        route: route.id,
        cause: err,
      });
    }
    const ms = now() - started;
    const responseTraceId = res.headers.get('x-trace-id') ?? traceId;
    this.#version_(res.headers);

    const quota = parseQuota(res.headers);
    const deprecated = res.headers.get('x-deprecated-fields');
    const traceEvent: TraceEvent = {
      traceId: responseTraceId,
      route: route.id,
      ms,
      status: res.status,
      ...(quota ? { quota } : {}),
      ...(deprecated
        ? {
            deprecatedFields: deprecated
              .split(',')
              .map((s) => s.trim())
              .filter(Boolean),
          }
        : {}),
      ...(res.status === 304 ? { cached: true } : {}),
    };

    if (res.status === 304) {
      if (cached === undefined) {
        this.#trace({ ...traceEvent, errorCode: 'INTERNAL' });
        throw new TerminalApiError({
          code: 'INTERNAL',
          message: `304 Not Modified for ${route.id} without a cached response`,
          status: 304,
          traceId: responseTraceId,
          route: route.id,
        });
      }
      this.#trace(traceEvent);
      return cached.value;
    }

    if (init.onResponseHeaders) init.onResponseHeaders(headersOf(res));

    const text = await res.text();

    if (!res.ok) {
      const error = this.#error(route, res, text, responseTraceId);
      this.#trace({ ...traceEvent, errorCode: error.code });
      throw error;
    }
    this.#trace(traceEvent);

    const contentType = res.headers.get('content-type') ?? '';
    if (contentType !== '' && !contentType.includes('json')) {
      // The §9 CSV exports. `wire/rest/export.ts` types them as `CsvDocument` (a `z.string()`),
      // so a route that declares a schema gets the validated text; one that does not gets the text
      // plus every response header (`content-disposition`, `x-provenance`, `x-as-of-*`).
      if (route.response !== null && init.skipResponseValidation !== true) {
        return this.#parseResponse(route, text, res.status, responseTraceId);
      }
      const out: TextResponse = { text, headers: headersOf(res) };
      return out;
    }

    if (text.trim() === '') return undefined;

    let json: unknown;
    try {
      json = JSON.parse(text) as unknown;
    } catch (err) {
      throw new TerminalApiError({
        code: 'VALIDATION_FAILED',
        message: `${route.id}: response was not valid JSON`,
        status: res.status,
        traceId: responseTraceId,
        details: { location: 'response' },
        route: route.id,
        cause: err,
      });
    }

    const value =
      route.response === null || init.skipResponseValidation === true
        ? json
        : this.#parseResponse(route, json, res.status, responseTraceId);

    if (cacheable) {
      const etag = res.headers.get('etag');
      if (etag !== null) this.#cache.set(cacheKey, { etag, value });
    }
    return value;
  }

  // ── internals ────────────────────────────────────────────────────────────

  #traceId(): string {
    const factory = this.options.traceId;
    return factory ? factory() : defaultTraceId();
  }

  #trace(event: TraceEvent): void {
    const sink = this.options.onTrace;
    if (!sink) return;
    try {
      sink(event);
    } catch {
      // a broken telemetry sink must never fail a request
    }
  }

  #version_(headers: Headers): void {
    const sink = this.options.onVersion;
    if (!sink) return;
    const serverVersion = headers.get('x-server-version');
    if (serverVersion === null) return;
    const next: VersionEvent = {
      serverVersion,
      minClientVersion: headers.get('x-min-client-version') ?? '',
      dictionaryVersion: headers.get('x-dictionary-version') ?? '',
    };
    const prev = this.#version;
    if (
      prev !== null &&
      prev.serverVersion === next.serverVersion &&
      prev.minClientVersion === next.minClientVersion &&
      prev.dictionaryVersion === next.dictionaryVersion
    ) {
      return;
    }
    this.#version = next;
    try {
      sink(next);
    } catch {
      // as above
    }
  }

  #route(routeId: string, traceId: string): IndexedRoute {
    const route = routes().get(routeId);
    if (route === undefined) {
      throw new TerminalApiError({
        code: 'NOT_FOUND',
        message: `unknown route '${routeId}' — wire/rest declares ${routes().size} routes`,
        status: 0,
        traceId,
        route: routeId,
      });
    }
    return route;
  }

  #validate(
    route: IndexedRoute,
    part: 'params' | 'query' | 'body',
    value: unknown,
    traceId: string,
  ): unknown {
    const schema = route[part];
    if (schema === null) return value;
    const input = value === undefined && part !== 'body' ? {} : value;
    const parsed = schema.safeParse(input);
    if (!parsed.success) {
      throw new TerminalApiError({
        code: 'VALIDATION_FAILED',
        message: `${route.id}: invalid request ${part}`,
        status: 0,
        traceId,
        details: { location: part, issues: issuesOf(parsed.error) },
        route: route.id,
      });
    }
    return parsed.data;
  }

  #parseResponse(route: IndexedRoute, json: unknown, status: number, traceId: string): unknown {
    const parsed = route.response!.safeParse(json);
    if (!parsed.success) {
      throw new TerminalApiError({
        code: 'VALIDATION_FAILED',
        message: `${route.id}: response did not match the wire schema`,
        status,
        traceId,
        details: { location: 'response', issues: issuesOf(parsed.error) },
        route: route.id,
      });
    }
    return parsed.data;
  }

  #error(route: IndexedRoute, res: Response, text: string, traceId: string): TerminalApiError {
    let json: unknown;
    try {
      json = text.trim() === '' ? undefined : (JSON.parse(text) as unknown);
    } catch {
      json = undefined;
    }
    const envelope = ErrorEnvelope.safeParse(json);
    if (envelope.success) {
      const e = envelope.data.error;
      return new TerminalApiError({
        code: e.code,
        message: e.message,
        status: res.status,
        traceId: e.traceId,
        retryable: e.retryable,
        retryAfterMs: e.retryAfterMs ?? this.#retryAfter(res),
        details: e.details,
        route: route.id,
      });
    }
    const message =
      isRecord(json) && isRecord(json.error) && typeof json.error.message === 'string'
        ? json.error.message
        : text.trim() === ''
          ? `${res.status} ${res.statusText}`
          : text.slice(0, 500);
    return new TerminalApiError({
      code: codeForStatus(res.status),
      message: `${route.id}: ${message}`,
      status: res.status,
      traceId,
      retryAfterMs: this.#retryAfter(res),
      route: route.id,
    });
  }

  #retryAfter(res: Response): number | undefined {
    const header = res.headers.get('retry-after');
    if (header === null) return undefined;
    const seconds = Number(header);
    return Number.isFinite(seconds) ? seconds * 1000 : undefined;
  }

  #url(route: IndexedRoute, params: unknown, query: unknown, traceId: string): string {
    const bag = isRecord(params) ? params : {};
    const withParams = route.spelling.replace(
      /:([A-Za-z0-9_]+)|\{([A-Za-z0-9_]+)\}/g,
      (_m: string, a: string | undefined, b: string | undefined): string => {
        const key = a ?? b ?? '';
        const value = bag[key];
        if (value === undefined || value === null) {
          throw new TerminalApiError({
            code: 'VALIDATION_FAILED',
            message: `${route.id}: missing path parameter '${key}'`,
            status: 0,
            traceId,
            details: { location: 'params', param: key },
            route: route.id,
          });
        }
        return encodeURIComponent(scalar(value));
      },
    );
    const search = new URLSearchParams();
    if (isRecord(query)) {
      for (const [key, value] of Object.entries(query)) {
        if (value === undefined || value === null) continue;
        if (Array.isArray(value)) {
          for (const item of value) {
            if (item === undefined || item === null) continue;
            search.append(key, scalar(item));
          }
        } else {
          search.append(key, scalar(value));
        }
      }
    }
    const qs = search.toString();
    return `${this.baseUrl}${withParams}${qs === '' ? '' : `?${qs}`}`;
  }
}

