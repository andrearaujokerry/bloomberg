function uncapitalise(s: string): string {
  return s.length === 0 ? s : `${s[0]!.toLowerCase()}${s.slice(1)}`;
}

function now(): number {
  return typeof performance !== 'undefined' && typeof performance.now === 'function'
    ? performance.now()
    : Date.now();
}

function defaultTraceId(): string {
  const webCrypto = (globalThis as { crypto?: { randomUUID?: () => string } }).crypto;
  if (typeof webCrypto?.randomUUID === 'function') return webCrypto.randomUUID();
  // Platforms without WebCrypto (old Node in a test harness) still need a syntactically valid uuid.
  const hex = '0123456789abcdef';
  let out = '';
  for (let i = 0; i < 36; i += 1) {
    if (i === 8 || i === 13 || i === 18 || i === 23) out += '-';
    else if (i === 14) out += '4';
    else if (i === 19) out += hex[8 + Math.floor(Math.random() * 4)]!;
    else out += hex[Math.floor(Math.random() * 16)]!;
  }
  return out;
}

function scalar(value: unknown): string {
  if (value instanceof Date) return value.toISOString();
  if (typeof value === 'object' && value !== null) return JSON.stringify(value);
  return String(value);
}

function issuesOf(error: { issues?: unknown } | undefined): unknown[] {
  const issues = error?.issues;
  return Array.isArray(issues) ? issues : [];
}

const STATUS_CODE: Readonly<Record<number, ErrorCode>> = {
  400: 'BAD_REQUEST',
  401: 'AUTH_REQUIRED',
  403: 'FORBIDDEN',
  404: 'NOT_FOUND',
  409: 'DUPLICATE_NAME',
  422: 'BAD_REQUEST',
  426: 'PROTOCOL_VERSION',
  429: 'RATE_LIMITED',
  500: 'INTERNAL',
  503: 'PROVIDER_UNAVAILABLE',
};

function codeForStatus(status: number): ErrorCode {
  return STATUS_CODE[status] ?? (status >= 500 ? 'INTERNAL' : 'BAD_REQUEST');
}

/** `x-quota-daily-instruments: 41/500` → `{ used: 41, limit: 500 }` (API.md L1160). */
function parseQuota(headers: Headers): Record<string, { used: number; limit: number }> | undefined {
  let found: Record<string, { used: number; limit: number }> | undefined;
  headers.forEach((value, key) => {
    if (!key.toLowerCase().startsWith('x-quota-')) return;
    const [used, limit] = value.split('/');
    const u = Number(used);
    const l = Number(limit);
    if (!Number.isFinite(u) || !Number.isFinite(l)) return;
    found ??= {};
    found[key.toLowerCase().slice('x-quota-'.length)] = { used: u, limit: l };
  });
  return found;
}

function isRawBody(value: unknown): boolean {
  if (value === undefined || value === null) return false;
  if (typeof value === 'string') return true;
  if (typeof Blob !== 'undefined' && value instanceof Blob) return true;
  if (typeof FormData !== 'undefined' && value instanceof FormData) return true;
  if (typeof URLSearchParams !== 'undefined' && value instanceof URLSearchParams) return true;
  if (value instanceof ArrayBuffer) return true;
  return ArrayBuffer.isView(value);
}

function headersOf(res: Response): Record<string, string> {
  const out: Record<string, string> = {};
  res.headers.forEach((value, key) => {
    out[key.toLowerCase()] = value;
  });
  return out;
}

