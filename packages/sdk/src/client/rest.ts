/**
 * `client/rest.ts` — the typed REST transport (API.md §10, §10.1).
 *
 * Everything here is **schema driven**: the route table is `wire/rest/*` reached through the
 * GENERATED barrel `wire/rest/index.ts`. Adding a route to the terminal therefore never touches this
 * file — a new `Rest.<Group>.<Route>` entry appears in the barrel and is immediately callable as
 * `rest.request('<Group>.<Route>', …)` and as `client.<group>.<route>(…)`.
 *
 * What a request does, in order:
 *   1. look the route up by id (`'Auth.Login'`) or by `(method, path)`;
 *   2. validate `params` / `query` / `body` locally with the route's zod schemas (a failure is a
 *      client-side `TerminalApiError { code:'VALIDATION_FAILED', details.location }` — no request
 *      leaves the process);
 *   3. build `baseUrl + '/api/v1' + path` with `:param` substitution and a `URLSearchParams` query;
 *   4. send `x-trace-id` (one per user action, OPS-07), `x-client-version`, and either
 *      `Authorization: Bearer …` (bearer mode) or `x-requested-with: terminal` on mutations plus
 *      `credentials:'include'` (cookie mode, API.md §1.3 L129 / §0 L59);
 *   5. honour `If-None-Match` for the ETag routes (`/universe/snapshot`, `/functions`, `/fields`;
 *      API.md L447, L493, L563) and answer a `304` from the in-memory cache;
 *   6. parse the body with the route's response schema, throwing `VALIDATION_FAILED` on drift;
 *   7. map the §2 error envelope to a typed `TerminalApiError`;
 *   8. surface `x-quota-*`, `x-deprecated-fields` through `onTrace` and `x-server-version` /
 *      `x-min-client-version` / `x-dictionary-version` through `onVersion` (§11).
 */
