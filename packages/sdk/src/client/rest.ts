export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' | 'HEAD';

/**
 * The shape every `wire/rest/<group>.ts` entry must have. Only `method` and `path` are required —
 * they are also what identifies an entry as a route rather than a plain zod schema exported from the
 * same module.
 */
export interface RouteDef {
  readonly method: HttpMethod;
  readonly path: string;
  readonly params?: z.ZodType;
  readonly query?: z.ZodType;
  readonly body?: z.ZodType;
  readonly response?: z.ZodType;
  /** Force (`true`) or forbid (`false`) the conditional-request cache; defaults to the §5 table. */
  readonly etag?: boolean;
  /** Non-JSON responses (the §9 CSV exports) — the value is sent as `accept`. */
  readonly accept?: string;
}

type RouteLike = { readonly method: string; readonly path: string };

/** The barrel exports either a `Rest` object of groups, or the groups themselves. Both work. */
type Barrel = typeof RestBarrel;
export type RestRegistry = Barrel extends { Rest: infer R } ? R : Barrel;

type Get<D, K extends PropertyKey> = K extends keyof D ? D[K] : undefined;
type Get2<D, G extends PropertyKey, K extends PropertyKey> = G extends keyof D
  ? K extends keyof D[G]
    ? D[G][K]
    : never
  : never;
type InputOf<S> = S extends z.ZodType ? z.input<S> : never;
type OutputOf<S> = S extends z.ZodType ? z.output<S> : never;
type Part<D, K extends string> = [InputOf<Get<D, K>>] extends [never]
  ? object
  : Record<K, InputOf<Get<D, K>>>;

/** `{ params?, query?, body? }`, each typed by the route's zod schema (API.md L1291). */
export type RouteArgs<D> = Part<D, 'params'> & Part<D, 'query'> & Part<D, 'body'>;

/** The route's decoded response, or `undefined` for the `204`s that declare no schema. */
export type RouteResponseOf<D> = [OutputOf<Get<D, 'response'>>] extends [never]
  ? undefined
  : OutputOf<Get<D, 'response'>>;

type Keys<T> = Extract<keyof T, string>;
/** Plain object literals (the group objects) have an implicit index signature; zod schemas — being
 * class instances — do not, which is what keeps the third level of the walk below off `z.ZodType`. */
type Nested<T> = T extends Record<string, unknown> ? T : never;
type UnionToIntersection<U> = (U extends unknown ? (x: U) => void : never) extends (
  x: infer I,
) => void
  ? I
  : never;

/**
 * Every `{ '<id>': def }` singleton the barrel yields, at any of the three nesting depths the
 * runtime `buildIndex()` accepts:
 *   1. `export const Rest = { Auth: { Login: {…} } }`       → 'Auth.Login'
 *   2. `export const Auth = { Login: {…} }` (re-exported)   → 'Auth.Login'
 *   3. `export * as auth from './auth.js'` — a namespace that *contains* `Auth` → 'Auth.Login'
 * Depth 3 names the route after the group object it found, not after the module namespace, so the
 * ids the type layer produces are exactly the ids `buildIndex()` registers.
 */
type RouteSingletons<R> = {
  [G in Keys<R>]: R[G] extends RouteLike
    ? Record<G, R[G]>
    : {
        [K in Keys<R[G]>]: R[G][K] extends RouteLike
          ? Record<`${G}.${K}`, R[G][K]>
          : {
              [S in Keys<Nested<R[G][K]>>]: Nested<R[G][K]>[S] extends RouteLike
                ? Record<`${K}.${S}`, Nested<R[G][K]>[S]>
                : never;
            }[Keys<Nested<R[G][K]>>];
      }[Keys<R[G]>];
}[Keys<R>];

/** Route id → route definition, for every route the barrel declares. */
export type RouteMap = UnionToIntersection<RouteSingletons<RestRegistry>>;

/** `'Auth.Login' | 'Data.Request' | 'Functions.Run' | …` — every route in the barrel. */
export type RouteId = Keys<RouteMap>;

/** The definition behind a `RouteId`. */
export type RouteDefOf<Id extends string> = Id extends keyof RouteMap
  ? RouteMap[Id]
  : Id extends keyof RestRegistry
    ? RestRegistry[Id]
    : Id extends `${infer G}.${infer K}`
      ? Get2<RestRegistry, G, K>
      : never;

/** The routes of one group, keyed by their short names — `GroupOf<'Auth'>['Login']`. */
export type GroupOf<G extends string> = {
  [Id in RouteId as Id extends `${G}.${infer K}` ? K : never]: RouteMap[Id];
};

export type RouteResponse<Id extends string> = RouteResponseOf<RouteDefOf<Id>>;

